SELECT COUNT(FISH_TYPE) AS FISH_COUNT, MAX(LENGTH) AS MAX_LENGTH, FISH_TYPE
FROM
# NULL(길이 10이하) -> 10으로 처리
(SELECT A.ID, A.FISH_TYPE,
    CASE
        WHEN A.LENGTH IS NULL THEN 10
        ELSE A.LENGTH
    END AS LENGTH
FROM FISH_INFO AS A) AS B
# 물고기 타입에 대해 GROUP BY + HAVING
GROUP BY FISH_TYPE
HAVING AVG(LENGTH) >= 33
ORDER BY FISH_TYPE ASC